function buildWorkspaceRouteAuditEntries(): UiRouteAuditEntry[] {
  return Object.values(DOMAIN_CONFIGS).flatMap((config) => {
    const seenPaths = new Set<string>();

    return config.workNavigation
      .flatMap((section) => section.items)
      .filter((item) => {
        if (seenPaths.has(item.path)) {
          return false;
        }
        seenPaths.add(item.path);
        return true;
      })
      .map((item) => ({
        id: `workspace-${config.domain.toLowerCase()}-${item.id}`,
        route: `/app${item.path}`,
        label: `${config.label} · ${item.label}`,
        scope: "workspace" as const,
        domain: config.domain,
        currentSource: WORKSPACE_DOMAIN_SOURCES[config.domain],
        targetSource: "@/components/l1/workspace/workspace-shell-new + canonical ui primitives",
        status: "restyle" as const,
        notes:
          config.domain === "PERSONAL"
            ? "Personal runtime routes still render through the BizOps registry and need extraction into the shared enterprise shell."
            : "Domain-scoped runtime module. Retain the route, replace local hardcoded styling with canonical tokens and primitives.",
      }));
  });
}

